<?php
/**
 * PhentiBuild - Excel Export Center
 * GET /backend/api/export/excel.php               General export (current BOQ + Materials catalog)
 * GET /backend/api/export/excel.php?projectId=5    Same export, with that project's info on sheet 1
 *
 * Streams a real, editable .xlsx workbook built by ExcelExportService —
 * see that file for the sheet-by-sheet structure. A successful export is
 * also recorded as a Report row (Report::create() already fires the
 * usual History::record() hook), so every export shows up in the
 * History & Audit Log like any other action.
 */

require_once __DIR__ . '/../../core/bootstrap.php';
require_once __DIR__ . '/../../models/Project.php';
require_once __DIR__ . '/../../models/BoqItem.php';
require_once __DIR__ . '/../../models/Material.php';
require_once __DIR__ . '/../../models/Report.php';
require_once __DIR__ . '/../../services/ExcelExportService.php';

phb_require_auth();

if ($_SERVER['REQUEST_METHOD'] !== 'GET') {
    Response::methodNotAllowed(['GET']);
}

$project = null;
if (!empty($_GET['projectId'])) {
    if (!ctype_digit((string) $_GET['projectId'])) {
        Response::error('Invalid projectId.', 400);
    }
    $project = (new Project(getDbConnection()))->find((int) $_GET['projectId']);
    if ($project === null) {
        Response::notFound('Project ' . $_GET['projectId'] . ' was not found.');
    }
}

$boqItems = (new BoqItem(getDbConnection()))->all();
$materials = (new Material(getDbConnection()))->all();

try {
    $spreadsheet = ExcelExportService::build($project, $boqItems, $materials);
} catch (Throwable $e) {
    error_log('[PhentiBuild Export] Failed to build workbook: ' . $e->getMessage());
    Response::serverError('Could not generate the Excel workbook.');
}

$filenameBase = $project !== null
    ? preg_replace('/[^A-Za-z0-9\-]+/', '-', $project['ref'] . '-' . $project['name'])
    : 'General';
$filename = 'PhentiBuild-Export-' . trim($filenameBase, '-') . '-' . date('Ymd-His') . '.xlsx';

(new Report(getDbConnection()))->create([
    'title' => $project !== null ? "Excel export — {$project['name']}" : 'Excel export — General',
    'type' => 'xlsx',
    'projectId' => $project['id'] ?? null,
    'content' => [
        'filename' => $filename,
        'boqItemCount' => count($boqItems),
        'materialCount' => count($materials),
    ],
    'notes' => 'Generated by the Excel Export Center.',
]);

while (ob_get_level() > 0) {
    ob_end_clean();
}

header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
header('Content-Disposition: attachment; filename="' . $filename . '"');
header('Cache-Control: max-age=0, must-revalidate');
header('Pragma: public');

$writer = new \PhpOffice\PhpSpreadsheet\Writer\Xlsx($spreadsheet);
$writer->save('php://output');
exit;
