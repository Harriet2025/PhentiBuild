<?php
/**
 * PhentiBuild - Excel Export Service
 *
 * Builds a real, editable .xlsx workbook (via PhpSpreadsheet — see
 * composer.json) from the app's own data: whichever project was asked
 * for (optional — BOQ/Materials/schedules are global collections, not
 * project-scoped, per how those modules were built), the current Bill
 * of Quantities, the active materials catalog, four BOQ-category
 * schedules, and a cost summary rolled up by category.
 *
 * Every sheet is plain data + formatting (no formulas tied to external
 * state), so the workbook opens and edits normally in Excel, LibreOffice
 * Calc, or Google Sheets without any "external link" prompts.
 */
require_once __DIR__ . '/../../vendor/autoload.php';

use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Fill;

final class ExcelExportService
{
    private const BRAND_ORANGE = 'FF6600';
    private const BRAND_DARK = '2B2B2B';
    private const HEADER_TEXT = 'FFFFFF';
    private const STRIPE = 'F8F9FA';
    private const BORDER_COLOR = 'D7D9DC';

    /** BOQ categories broken out into their own dedicated schedule sheet. */
    private const SCHEDULE_CATEGORIES = ['Cement', 'Rebar', 'Timber', 'Roofing'];

    /**
     * @param array|null $project   Project::find() row, or null for a general export
     * @param array      $boqItems  BoqItem::all() rows
     * @param array      $materials Material::all() rows (active only)
     */
    public static function build(?array $project, array $boqItems, array $materials): Spreadsheet
    {
        $spreadsheet = new Spreadsheet();
        $spreadsheet->getProperties()
            ->setCreator(APP_NAME)
            ->setLastModifiedBy(APP_NAME)
            ->setTitle(($project['name'] ?? 'General') . ' - ' . APP_NAME . ' Export')
            ->setSubject('Construction project export')
            ->setDescription('Generated by the ' . APP_NAME . ' Excel Export Center on ' . date('Y-m-d H:i'))
            ->setCategory('Construction Estimation');

        self::buildProjectInfoSheet($spreadsheet->getActiveSheet(), $project, $boqItems, $materials);
        self::buildBoqSheet($spreadsheet->createSheet(), $boqItems);
        self::buildMaterialsSheet($spreadsheet->createSheet(), $materials);

        foreach (self::SCHEDULE_CATEGORIES as $category) {
            self::buildScheduleSheet($spreadsheet->createSheet(), $category . ' Schedule', $boqItems, $category);
        }

        self::buildCostSummarySheet($spreadsheet->createSheet(), $boqItems, $project);

        $spreadsheet->setActiveSheetIndex(0);
        return $spreadsheet;
    }

    /* =================================================================
       Sheet builders
       ================================================================= */

    private static function buildProjectInfoSheet(Worksheet $sheet, ?array $project, array $boqItems, array $materials): void
    {
        $sheet->setTitle('Project Information');
        self::pageTitle($sheet, 'A1:D1', APP_NAME . ' — Project Information');

        $row = 3;
        if ($project !== null) {
            $facts = [
                ['Project Reference', $project['ref']],
                ['Project Name', $project['name']],
                ['Client', $project['client']],
                ['Contact', $project['contact']],
                ['Location', $project['location']],
                ['Project Type', $project['type']],
                ['Status', $project['status']],
                ['Progress', (int) $project['progress'] . '%'],
                ['Start Date', $project['start_date']],
                ['Expected Completion', $project['end_date']],
                ['Description', $project['description'] ?: '—'],
            ];
        } else {
            $facts = [
                ['Project Reference', 'General Export — no project selected'],
                ['Note', 'This workbook covers the current BOQ and Materials catalog, not a specific project.'],
            ];
        }

        foreach ($facts as [$label, $value]) {
            $sheet->setCellValue("A{$row}", $label);
            $sheet->setCellValue("B{$row}", $value);
            $sheet->getStyle("A{$row}")->getFont()->setBold(true);
            $sheet->getStyle("A{$row}")->getFont()->setColor(new \PhpOffice\PhpSpreadsheet\Style\Color(self::BRAND_DARK));
            $row++;
        }

        $row += 1;
        $sheet->setCellValue("A{$row}", 'Export Summary');
        $sheet->getStyle("A{$row}")->getFont()->setBold(true)->setSize(12);
        $row++;

        $totalCost = array_sum(array_column($boqItems, 'total'));
        $summary = [
            ['BOQ Line Items', count($boqItems)],
            ['Materials in Catalog', count($materials)],
            ['Total Estimated Cost', $totalCost],
            ['Report Generated', date('Y-m-d H:i')],
        ];
        foreach ($summary as [$label, $value]) {
            $sheet->setCellValue("A{$row}", $label);
            $sheet->setCellValue("B{$row}", $value);
            $sheet->getStyle("A{$row}")->getFont()->setBold(true);
            if ($label === 'Total Estimated Cost') {
                $sheet->getStyle("B{$row}")->getNumberFormat()->setFormatCode('#,##0.00');
            }
            $row++;
        }

        $sheet->getColumnDimension('A')->setWidth(26);
        $sheet->getColumnDimension('B')->setWidth(46);
        $sheet->getColumnDimension('C')->setWidth(18);
        $sheet->getColumnDimension('D')->setWidth(18);
    }

    private static function buildBoqSheet(Worksheet $sheet, array $boqItems): void
    {
        $sheet->setTitle('BOQ');
        self::pageTitle($sheet, 'A1:J1', 'Bill of Quantities');

        $headers = ['ID', 'Item', 'Category', 'Description', 'Specification', 'Unit', 'Quantity', 'Waste %', 'Unit Price', 'Total'];
        $headerRow = 3;
        self::writeHeaderRow($sheet, $headerRow, $headers);

        $row = $headerRow + 1;
        foreach ($boqItems as $item) {
            $sheet->setCellValue("A{$row}", $item['id']);
            $sheet->setCellValue("B{$row}", $item['item']);
            $sheet->setCellValue("C{$row}", $item['category']);
            $sheet->setCellValue("D{$row}", $item['description']);
            $sheet->setCellValue("E{$row}", $item['specification']);
            $sheet->setCellValue("F{$row}", $item['unit']);
            $sheet->setCellValue("G{$row}", $item['quantity']);
            $sheet->setCellValue("H{$row}", $item['waste_percent']);
            $sheet->setCellValue("I{$row}", $item['unit_price']);
            $sheet->setCellValue("J{$row}", $item['total']);
            $row++;
        }
        $lastDataRow = $row - 1;

        if ($lastDataRow >= $headerRow + 1) {
            $firstDataRow = $headerRow + 1;
            $sheet->getStyle("G{$firstDataRow}:G{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.000');
            $sheet->getStyle("H{$firstDataRow}:H{$lastDataRow}")->getNumberFormat()->setFormatCode('0.00"%"');
            $sheet->getStyle("I{$firstDataRow}:I{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.00');
            $sheet->getStyle("J{$firstDataRow}:J{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.00');
        }

        $row++;
        $sheet->setCellValue("I{$row}", 'Grand Total');
        $sheet->setCellValue("J{$row}", array_sum(array_column($boqItems, 'total')));
        self::styleTotalRow($sheet, $row, 'I', 'J');

        self::applyTableBorders($sheet, $headerRow, $lastDataRow, count($headers));
        self::autoSizeColumns($sheet, count($headers));
        $sheet->freezePane("A" . ($headerRow + 1));

        if (empty($boqItems)) {
            $sheet->setCellValue("A{$headerRow}1", 'No BOQ items have been added yet.');
        }
    }

    private static function buildMaterialsSheet(Worksheet $sheet, array $materials): void
    {
        $sheet->setTitle('Materials');
        self::pageTitle($sheet, 'A1:H1', 'Materials Catalog');

        $headers = ['ID', 'Name', 'Category', 'Unit', 'Dimensions', 'Overall Dimensions', 'Effective Coverage', 'Standard Length'];
        $headerRow = 3;
        self::writeHeaderRow($sheet, $headerRow, $headers);

        $row = $headerRow + 1;
        foreach ($materials as $m) {
            $sheet->setCellValue("A{$row}", $m['id']);
            $sheet->setCellValue("B{$row}", $m['name']);
            $sheet->setCellValue("C{$row}", $m['category']);
            $sheet->setCellValue("D{$row}", $m['unit']);
            $sheet->setCellValue("E{$row}", $m['dimensions']);
            $sheet->setCellValue("F{$row}", $m['overall_dimensions']);
            $sheet->setCellValue("G{$row}", $m['effective_coverage']);
            $sheet->setCellValue("H{$row}", $m['standard_length']);
            $row++;
        }
        $lastDataRow = $row - 1;

        self::applyTableBorders($sheet, $headerRow, $lastDataRow, count($headers));
        self::autoSizeColumns($sheet, count($headers));
        $sheet->freezePane("A" . ($headerRow + 1));
    }

    private static function buildScheduleSheet(Worksheet $sheet, string $title, array $boqItems, string $category): void
    {
        $sheet->setTitle($title);
        self::pageTitle($sheet, 'A1:H1', $title);

        $items = array_values(array_filter($boqItems, fn(array $i): bool => $i['category'] === $category));

        $headers = ['ID', 'Item', 'Description', 'Specification', 'Unit', 'Quantity', 'Unit Price', 'Total'];
        $headerRow = 3;
        self::writeHeaderRow($sheet, $headerRow, $headers);

        $row = $headerRow + 1;
        foreach ($items as $item) {
            $sheet->setCellValue("A{$row}", $item['id']);
            $sheet->setCellValue("B{$row}", $item['item']);
            $sheet->setCellValue("C{$row}", $item['description']);
            $sheet->setCellValue("D{$row}", $item['specification']);
            $sheet->setCellValue("E{$row}", $item['unit']);
            $sheet->setCellValue("F{$row}", $item['quantity']);
            $sheet->setCellValue("G{$row}", $item['unit_price']);
            $sheet->setCellValue("H{$row}", $item['total']);
            $row++;
        }
        $lastDataRow = $row - 1;

        if ($lastDataRow >= $headerRow + 1) {
            $sheet->getStyle("F" . ($headerRow + 1) . ":F{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.000');
            $sheet->getStyle("G" . ($headerRow + 1) . ":G{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.00');
            $sheet->getStyle("H" . ($headerRow + 1) . ":H{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.00');
        }

        $row++;
        $sheet->setCellValue("G{$row}", 'Subtotal');
        $sheet->setCellValue("H{$row}", array_sum(array_column($items, 'total')));
        self::styleTotalRow($sheet, $row, 'G', 'H');

        self::applyTableBorders($sheet, $headerRow, $lastDataRow, count($headers));
        self::autoSizeColumns($sheet, count($headers));
        $sheet->freezePane("A" . ($headerRow + 1));

        if (empty($items)) {
            $sheet->setCellValue("A" . ($headerRow + 1), "No {$category} items are in the current BOQ.");
        }
    }

    private static function buildCostSummarySheet(Worksheet $sheet, array $boqItems, ?array $project): void
    {
        $sheet->setTitle('Cost Summary');
        self::pageTitle($sheet, 'A1:D1', 'Cost Summary' . ($project ? ' — ' . $project['name'] : ''));

        $headers = ['Category', 'Line Items', 'Total Quantity Value', 'Total Cost'];
        $headerRow = 3;
        self::writeHeaderRow($sheet, $headerRow, $headers);

        $byCategory = [];
        foreach ($boqItems as $item) {
            $cat = $item['category'];
            if (!isset($byCategory[$cat])) {
                $byCategory[$cat] = ['count' => 0, 'qty' => 0.0, 'total' => 0.0];
            }
            $byCategory[$cat]['count']++;
            $byCategory[$cat]['qty'] += $item['adjusted_quantity'];
            $byCategory[$cat]['total'] += $item['total'];
        }
        ksort($byCategory);

        $row = $headerRow + 1;
        foreach ($byCategory as $category => $stats) {
            $sheet->setCellValue("A{$row}", $category);
            $sheet->setCellValue("B{$row}", $stats['count']);
            $sheet->setCellValue("C{$row}", $stats['qty']);
            $sheet->setCellValue("D{$row}", $stats['total']);
            $row++;
        }
        $lastDataRow = $row - 1;

        if ($lastDataRow >= $headerRow + 1) {
            $sheet->getStyle("C" . ($headerRow + 1) . ":C{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.000');
            $sheet->getStyle("D" . ($headerRow + 1) . ":D{$lastDataRow}")->getNumberFormat()->setFormatCode('#,##0.00');
        }

        $row++;
        $sheet->setCellValue("A{$row}", 'GRAND TOTAL');
        $sheet->setCellValue("B{$row}", count($boqItems));
        $sheet->setCellValue("D{$row}", array_sum(array_column($boqItems, 'total')));
        $sheet->mergeCells("A{$row}:A{$row}");
        self::styleTotalRow($sheet, $row, 'A', 'D');
        $sheet->getStyle("D{$row}")->getNumberFormat()->setFormatCode('#,##0.00');

        self::applyTableBorders($sheet, $headerRow, $lastDataRow, count($headers));
        self::autoSizeColumns($sheet, count($headers));
        $sheet->freezePane("A" . ($headerRow + 1));

        if (empty($boqItems)) {
            $sheet->setCellValue("A" . ($headerRow + 1), 'No BOQ items to summarize yet.');
        }
    }

    /* =================================================================
       Shared styling helpers
       ================================================================= */

    private static function pageTitle(Worksheet $sheet, string $range, string $title): void
    {
        $sheet->mergeCells($range);
        $firstCell = explode(':', $range)[0];
        $sheet->setCellValue($firstCell, $title);
        $sheet->getStyle($firstCell)->getFont()->setBold(true)->setSize(15)->getColor()->setRGB(self::BRAND_DARK);
        $sheet->getStyle($firstCell)->getAlignment()->setVertical(Alignment::VERTICAL_CENTER);
        $sheet->getRowDimension(1)->setRowHeight(26);

        // A thin orange accent rule under the title, brand-colored.
        $sheet->getStyle($range)->getBorders()->getBottom()
            ->setBorderStyle(Border::BORDER_MEDIUM)
            ->getColor()->setRGB(self::BRAND_ORANGE);
    }

    private static function writeHeaderRow(Worksheet $sheet, int $row, array $headers): void
    {
        $col = 'A';
        foreach ($headers as $header) {
            $sheet->setCellValue("{$col}{$row}", $header);
            $col++;
        }
        $lastCol = chr(ord('A') + count($headers) - 1);
        $range = "A{$row}:{$lastCol}{$row}";

        $sheet->getStyle($range)->getFont()->setBold(true)->getColor()->setRGB(self::HEADER_TEXT);
        $sheet->getStyle($range)->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setRGB(self::BRAND_DARK);
        $sheet->getStyle($range)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_LEFT)->setVertical(Alignment::VERTICAL_CENTER);
        $sheet->getRowDimension($row)->setRowHeight(20);
    }

    private static function styleTotalRow(Worksheet $sheet, int $row, string $fromCol, string $toCol): void
    {
        $range = "{$fromCol}{$row}:{$toCol}{$row}";
        $sheet->getStyle($range)->getFont()->setBold(true);
        $sheet->getStyle($range)->getBorders()->getTop()->setBorderStyle(Border::BORDER_THIN)->getColor()->setRGB(self::BRAND_DARK);
        $sheet->getStyle($range)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('FFEDE0');
    }

    private static function applyTableBorders(Worksheet $sheet, int $headerRow, int $lastDataRow, int $colCount): void
    {
        if ($lastDataRow < $headerRow) {
            return;
        }
        $lastCol = chr(ord('A') + $colCount - 1);
        $range = "A{$headerRow}:{$lastCol}{$lastDataRow}";

        $sheet->getStyle($range)->getBorders()->getAllBorders()
            ->setBorderStyle(Border::BORDER_THIN)
            ->getColor()->setRGB(self::BORDER_COLOR);

        // Zebra-striped data rows for readability.
        for ($r = $headerRow + 1; $r <= $lastDataRow; $r++) {
            if (($r - $headerRow) % 2 === 0) {
                $sheet->getStyle("A{$r}:{$lastCol}{$r}")->getFill()
                    ->setFillType(Fill::FILL_SOLID)
                    ->getStartColor()->setRGB(self::STRIPE);
            }
        }
    }

    private static function autoSizeColumns(Worksheet $sheet, int $colCount): void
    {
        for ($i = 0; $i < $colCount; $i++) {
            $col = chr(ord('A') + $i);
            $sheet->getColumnDimension($col)->setAutoSize(true);
        }
    }
}
